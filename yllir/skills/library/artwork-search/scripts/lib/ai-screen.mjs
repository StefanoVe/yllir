// Deterministic anti-AI screen for downloaded artwork candidates. A candidate is
// accepted only when no generative-AI marker appears in its text or in the image
// file's metadata, and when either its author declared it human-made or its
// publication date shows it predates the generative-AI wave.
// Fail-closed: ok is true only when reasons is empty. Pure function, no I/O, never throws.

const DEFAULT_CUTOFF = '2022-08-01';

// Phrases that declare a work human-made. They are stripped before the text markers
// are matched, so that "no AI" does not trigger "ai art" and similar markers.
const NO_AI_DECLARATION = /(?<![a-z0-9])(?:no[ -]?ai|noai|human[ -]made|made without ai)(?![a-z0-9])/g;

// Text markers, matched on the normalized text (lowercase, accents folded).
// Words may be separated by a space, a hyphen or an underscore.
const TEXT_PHRASES = [
  'midjourney',
  'stable diffusion',
  'stablediffusion',
  'sdxl',
  'dall-e',
  'dall e',
  'dalle',
  'firefly',
  'ai generated',
  'ai-generated',
  'ai art',
  'ai image',
  'ai-art',
  'made with ai',
  'generated by ai',
  'generative',
  'text to image',
  'text-to-image',
  'txt2img',
  'niji',
  'civitai',
  'novelai',
  'leonardo.ai',
  'prompt:',
  'negative prompt',
  'lora',
  'comfyui',
  'nightcafe',
  'playground ai',
  'craiyon',
  'bing image creator',
  'copilot designer',
  'gemini',
  'imagen',
  'flux',
  '#aiart',
  'aigenerated',
];

// Byte strings searched in the image file, read as latin1 and lowercased.
const BINARY_MARKERS = [
  'c2pa',
  'jumbf',
  'trainedalgorithmicmedia',
  'compositewithtrainedalgorithmicmedia',
  'algorithmicmedia',
  'midjourney',
  'stable diffusion',
  'dall-e',
  'firefly',
  'novelai',
  'comfyui',
  'negative prompt',
  'sd-metadata',
  'invokeai',
];

// Generation settings written as "steps: ... sampler: ..." within 200 characters.
const STEPS_SAMPLER = /steps:[\s\S]{0,200}?sampler:/;

const TEXT_MARKERS = TEXT_PHRASES.map((phrase) => ({
  name: slug(phrase),
  pattern: new RegExp(phraseSource(phrase)),
}));

/**
 * Screens one artwork candidate.
 * @param {object} cand candidate: pageUrl, imageUrl, title, author, tags, pageText, publishedAt, declaredNoAi
 * @param {{ bytes?: Buffer|null, cutoff?: string }} [options] bytes of the image file, date before which undeclared works pass
 * @returns {{ ok: boolean, reasons: string[] }}
 */
export function screenCandidate(cand, options) {
  try {
    return evaluate(cand, options);
  } catch {
    return result(['bad-input']);
  }
}

function evaluate(cand, options) {
  const opts = isRecord(options) ? options : {};
  const bytes = opts.bytes === undefined ? null : opts.bytes;
  const cutoff = opts.cutoff === undefined ? DEFAULT_CUTOFF : opts.cutoff;
  if (!isRecord(cand) || !hasValidShape(cand, bytes, cutoff)) return result(['bad-input']);

  const reasons = [];
  if (typeof cand.pageUrl !== 'string' || !cand.pageUrl.startsWith('https://')) reasons.push('bad-page-url');
  reasons.push(...textReasons(cand));
  reasons.push(...binaryReasons(bytes));
  reasons.push(...datingReasons(cand, cutoff));
  return result(reasons);
}

function result(reasons) {
  const unique = [...new Set(reasons)];
  return { ok: unique.length === 0, reasons: unique };
}

function hasValidShape(cand, bytes, cutoff) {
  if (typeof cand.title !== 'string' || typeof cand.pageText !== 'string' || typeof cand.imageUrl !== 'string') {
    return false;
  }
  if (!Array.isArray(cand.tags) || !cand.tags.every((tag) => typeof tag === 'string')) return false;
  if (typeof cand.declaredNoAi !== 'boolean') return false;
  if (cand.author !== undefined && cand.author !== null && typeof cand.author !== 'string') return false;
  if (cand.publishedAt !== undefined && cand.publishedAt !== null && typeof cand.publishedAt !== 'string') return false;
  if (bytes !== null && !Buffer.isBuffer(bytes)) return false;
  if (typeof cutoff !== 'string' || Number.isNaN(Date.parse(cutoff))) return false;
  return true;
}

function textReasons(cand) {
  const pageUrl = typeof cand.pageUrl === 'string' ? cand.pageUrl : '';
  const raw = [cand.title, ...cand.tags, cand.pageText, pageUrl, cand.imageUrl].join('\n');
  const text = normalize(raw).replace(NO_AI_DECLARATION, ' ');
  return TEXT_MARKERS.filter((marker) => marker.pattern.test(text)).map((marker) => `marker:${marker.name}`);
}

function binaryReasons(bytes) {
  if (bytes === null || bytes.length === 0) return ['no-bytes'];
  const text = bytes.toString('latin1').toLowerCase();
  const reasons = BINARY_MARKERS.filter((name) => text.includes(name)).map((name) => `metadata:${slug(name)}`);
  if (STEPS_SAMPLER.test(text)) reasons.push('metadata:steps-sampler');
  return reasons;
}

function datingReasons(cand, cutoff) {
  if (cand.declaredNoAi) return [];
  const published = parseDate(cand.publishedAt);
  if (published === null) return ['undated'];
  if (published >= Date.parse(cutoff)) return ['recent-undeclared'];
  return [];
}

function parseDate(value) {
  if (typeof value !== 'string' || !/^\d{4}-\d{2}-\d{2}/.test(value)) return null;
  const ms = Date.parse(value);
  return Number.isNaN(ms) ? null : ms;
}

// Lowercases and removes accents, so that matching ignores case and diacritics.
function normalize(text) {
  return text.normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase();
}

// Builds a regex source: tokens separated by any run of space, hyphen or underscore,
// with word boundaries on the sides that start or end with a letter or digit.
function phraseSource(phrase) {
  const body = phrase
    .split(/[\s_-]+/)
    .map((token) => token.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'))
    .join('[\\s_-]+');
  const head = /^[a-z0-9]/.test(phrase) ? '(?<![a-z0-9])' : '';
  const tail = /[a-z0-9]$/.test(phrase) ? '(?![a-z0-9])' : '';
  return head + body + tail;
}

function slug(text) {
  return text.replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');
}

function isRecord(value) {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}
