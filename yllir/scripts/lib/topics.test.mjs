test('new truncates the slug to 40 characters without a trailing hyphen', () => {
  const root = tmp();
  const goal = 'A very long goal about the tavern where the party meets the stranger tonight';
  const r = newTopic(root, { process: 'scene', goal, now: T1 });
  const slug = r.id.slice('2026-11-07-'.length);
  assert.equal(slug, slugify(goal).slice(0, 40).replace(/-+$/, ''));
  assert.ok(slug.length <= 40);
  assert.ok(!slug.endsWith('-'));
});

test('new pauses the previously current topic and orders the index', () => {
  const root = tmp();
  const a = newTopic(root, { process: 'scene', goal: 'Alpha', now: T1 });
  const b = newTopic(root, { process: 'scene', goal: 'Beta', now: T2 });
  assert.match(readHandoff(root, a.id), /^status: paused$/m);
  assert.match(readHandoff(root, b.id), /^status: active$/m);
  const c = newTopic(root, { process: 'scene', goal: 'Gamma', now: T3 });
  assert.deepEqual(
    listTopics(root).map((e) => [e.id, e.status]),
    [
      [c.id, 'active'],
      [b.id, 'paused'],
      [a.id, 'paused'],
    ],
  );
  assert.match(indexText(root), /\| active \| 2026-11-07-gamma \|/);
});

test('touch keeps hand-edited prose and rewrites Files with hashes', () => {
  const root = tmp();
  const r = newTopic(root, { process: 'prepare-session', goal: 'Prepare session 4', now: T1 });
  fs.mkdirSync(path.join(root, 'Trama', 'Arc'), { recursive: true });
  fs.writeFileSync(path.join(root, 'Trama', 'Arc', 'Session 4.md'), 'hello');
  const edited = readHandoff(root, r.id).replace(
    '## Decisions\n\n',
    '## Decisions\n\n- Il master vuole la taverna sul porto.\n',
  );
  fs.writeFileSync(handoffPath(root, r.id), edited);

  const res = touchTopic(root, {
    id: r.id,
    files: ['Trama/Arc/Session 4.md', 'Cronaca/missing.md'],
    now: T2,
  });
  assert.deepEqual(res, { id: r.id, changedSections: ['Files'] });

  const text = readHandoff(root, r.id);
  assert.ok(text.includes('- Il master vuole la taverna sul porto.\n'));
  assert.ok(text.includes('updated: 2026-11-07T17:00:00.000Z'));
  assert.ok(
    text.includes(
      `## Files\n\n- \`Trama/Arc/Session 4.md\` — sha256 ${sha('hello')}\n- \`Cronaca/missing.md\` — missing\n\n## Done`,
    ),
  );
  assert.match(indexText(root), /2026-11-07T17:00:00.000Z/);
});

test('touch reports no changed sections when nothing changed, and keeps prior files', () => {
  const root = tmp();
  const r = newTopic(root, { process: 'scene', goal: 'Docks', now: T1 });
  fs.mkdirSync(path.join(root, 'Trama'), { recursive: true });
  fs.writeFileSync(path.join(root, 'Trama', 'a.md'), 'a');
  touchTopic(root, { id: r.id, files: ['Trama/a.md', 'Trama/b.md'], now: T2 });
  const again = touchTopic(root, { id: r.id, files: [], now: T3 });
  assert.deepEqual(again.changedSections, []);

  fs.writeFileSync(path.join(root, 'Trama', 'b.md'), 'b');
  const later = touchTopic(root, { id: r.id, files: ['Trama/c.md'], now: T4 });
  assert.deepEqual(later.changedSections, ['Files']);
  const text = readHandoff(root, r.id);
  assert.ok(text.includes(`- \`Trama/a.md\` — sha256 ${sha('a')}\n`));
  assert.ok(text.includes(`- \`Trama/b.md\` — sha256 ${sha('b')}\n`));
  assert.ok(text.includes('- `Trama/c.md` — missing\n'));
});

test('touch refuses a handoff with a deleted section, and does not rewrite it', () => {
  const root = tmp();
  const r = newTopic(root, { process: 'scene', goal: 'Docks', now: T1 });
  const broken = readHandoff(root, r.id).replace('## Done\n\n', '');
  fs.writeFileSync(handoffPath(root, r.id), broken);
  expectError(() => touchTopic(root, { id: r.id, now: T2 }), 'bad-handoff', 'Done');
  assert.equal(readHandoff(root, r.id), broken);
});

test('activate and close update status, index and order', () => {
  const root = tmp();
  const a = newTopic(root, { process: 'scene', goal: 'Alpha', now: T1 });
  const b = newTopic(root, { process: 'scene', goal: 'Beta', now: T2 });
  activateTopic(root, { id: a.id, now: T3 });
  assert.deepEqual(
    listTopics(root).map((e) => [e.id, e.status]),
    [
      [a.id, 'active'],
      [b.id, 'paused'],
    ],
  );
  assert.equal(activeTopic(root).id, a.id);

  closeTopic(root, { id: a.id, now: T4 });
  assert.equal(activeTopic(root), null);
  assert.deepEqual(
    listTopics(root).map((e) => [e.id, e.status]),
    [
      [b.id, 'paused'],
      [a.id, 'closed'],
    ],
  );
  assert.match(indexText(root), /\| closed \| 2026-11-07-alpha \| scene \| Alpha \| 2026-11-07T19:00:00.000Z \|/);
});

