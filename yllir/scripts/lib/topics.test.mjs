test('checkTopic reports files edited, deleted or created since the handoff', () => {
  const root = tmp();
  const r = newTopic(root, { process: 'scene', goal: 'Docks', now: T1 });
  fs.mkdirSync(path.join(root, 'Trama'), { recursive: true });
  fs.writeFileSync(path.join(root, 'Trama', 'a.md'), 'a');
  fs.writeFileSync(path.join(root, 'Trama', 'b.md'), 'b');
  touchTopic(root, { id: r.id, files: ['Trama/a.md', 'Trama/b.md', 'Trama/never.md'], now: T2 });

  assert.deepEqual(checkTopic(root, { id: r.id }), { id: r.id, changed: [] });

  fs.writeFileSync(path.join(root, 'Trama', 'a.md'), 'a changed');
  fs.rmSync(path.join(root, 'Trama', 'b.md'));
  assert.deepEqual(checkTopic(root, { id: r.id }).changed, ['Trama/a.md', 'Trama/b.md']);

  // A file recorded as missing and still missing is not a change.
  fs.writeFileSync(path.join(root, 'Trama', 'a.md'), 'a');
  fs.writeFileSync(path.join(root, 'Trama', 'b.md'), 'b');
  assert.deepEqual(checkTopic(root, { id: r.id }).changed, []);
  fs.writeFileSync(path.join(root, 'Trama', 'never.md'), 'new');
  assert.deepEqual(checkTopic(root, { id: r.id }).changed, ['Trama/never.md']);
});

