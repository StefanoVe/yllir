function tmp() {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'yllir-topics-'));
  created.push(dir);
  return dir;
}

function at(iso) {
  return new Date(iso);
}

const T1 = at('2026-11-07T16:00:00.000Z');
const T2 = at('2026-11-07T17:00:00.000Z');
const T3 = at('2026-11-07T18:00:00.000Z');
const T4 = at('2026-11-07T19:00:00.000Z');

function sha(text) {
  return crypto.createHash('sha256').update(text).digest('hex');
}

function handoffPath(root, id) {
  return path.join(root, '.campaign', 'state', 'topics', `${id}.md`);
}

function readHandoff(root, id) {
  return fs.readFileSync(handoffPath(root, id), 'utf8');
}

function indexText(root) {
  return fs.readFileSync(path.join(root, '.campaign', 'state', 'topics', 'index.md'), 'utf8');
}

function expectError(fn, code, messagePart) {
  let caught = null;
  try {
    fn();
  } catch (err) {
    caught = err;
  }
  assert.ok(caught, `expected ${code} to be thrown`);
  assert.equal(caught.code, code);
  if (messagePart) assert.ok(caught.message.includes(messagePart), caught.message);
}

