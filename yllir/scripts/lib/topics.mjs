// Topics: one handoff file per topic of work (a scene, a place, a session being
// prepared) under .campaign/state/topics/, plus a generated index.md.
// The script owns the metadata, the file fingerprints and the index. The prose
// sections are written by agents and are kept byte for byte, except the Files
// section, which this module rewrites, and the `updated` / `status` fields.
// Every call is synchronous and uses only Node built-ins.

import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { parseFrontmatter } from './frontmatter.mjs';
import { slugify } from './normalize.mjs';

export const STATUSES = ['active', 'paused', 'closed'];

export const REQUIRED_SECTIONS = [
  'Goal',
  'Decisions',
  'Files',
  'Done',
  'Remaining',
  'Questions for the master',
  'Next step',
];

const TOPICS_DIR = path.join('.campaign', 'state', 'topics');
const INDEX_NAME = 'index.md';
const INDEX_HEADER = '<!-- Generated by Yllir. Do not edit. -->';
const ID_PATTERN = /^[a-z0-9][a-z0-9-]*$/;
const FILE_LINE = /^- `([^`]+)` — (sha256 ([0-9a-f]{64})|missing)$/;
const STATUS_RANK = { active: 0, paused: 1, closed: 2 };

function fail(code, message) {
  return Object.assign(new Error(message), { code });
}

/** Returns the resolved root, or throws bad-input when it is not a directory. */
function requireRoot(root) {
  if (typeof root !== 'string' || root === '') {
    throw fail('bad-input', 'root must be a path');
  }
  let stat = null;
  try {
    stat = fs.statSync(root);
  } catch {
    throw fail('bad-input', `${root} does not exist`);
  }
  if (!stat.isDirectory()) {
    throw fail('bad-input', `${root} is not a directory`);
  }
  return path.resolve(root);
}

function checkId(id) {
  if (typeof id !== 'string' || !ID_PATTERN.test(id) || id === 'index') {
    throw fail('bad-input', `invalid topic id: ${String(id)}`);
  }
}

function checkDate(now) {
  if (!(now instanceof Date) || Number.isNaN(now.getTime())) {
    throw fail('bad-input', 'now must be a valid Date');
  }
}

function checkGoal(goal) {
  if (typeof goal !== 'string' || goal.trim() === '') {
    throw fail('bad-input', 'goal must be a non-empty string');
  }
  if (/[\r\n]/.test(goal) || goal.trim().startsWith('#')) {
    throw fail('bad-input', 'goal must be one line and must not start with #');
  }
  return goal.trim();
}

/** A campaign-relative path, with forward slashes and no `..`, `.` or empty segments. */
function checkRelPath(p) {
  if (typeof p !== 'string' || p.trim() === '') {
    throw fail('bad-input', 'file paths must be non-empty strings');
  }
  const s = p.trim();
  const unsafe =
    s.startsWith('/') ||
    /^[A-Za-z]:/.test(s) ||
    s.includes('\\') ||
    s.includes('`') ||
    /[\r\n]/.test(s) ||
    s.split('/').some((seg) => seg === '' || seg === '.' || seg === '..');
  if (unsafe) {
    throw fail('bad-input', `file path must be campaign-relative: ${s}`);
  }
  return s;
}

function topicsDir(root) {
  return path.join(root, TOPICS_DIR);
}

function handoffFile(root, id) {
  return path.join(topicsDir(root), `${id}.md`);
}

function stripCr(line) {
  return line.endsWith('\r') ? line.slice(0, -1) : line;
}

/** Index of the closing `---` line of the frontmatter, or -1. */
function findClose(lines) {
  if (stripCr(lines[0]) !== '---') return -1;
  for (let i = 1; i < lines.length; i++) {
    if (stripCr(lines[i]) === '---') return i;
  }
  return -1;
}

/** Headings of level 1 or 2 found outside fenced code, from line index `from`. */
function headings(lines, from) {
  const found = [];
  let fence = null;
  for (let i = from; i < lines.length; i++) {
    const line = stripCr(lines[i]);
    const fenceMatch = /^(```|~~~)/.exec(line);
    if (fenceMatch) {
      if (fence === null) fence = fenceMatch[1];
      else if (fence === fenceMatch[1]) fence = null;
      continue;
    }
    if (fence !== null) continue;
    const m = /^(#{1,2}) (.*)$/.exec(line);
    if (m) found.push({ index: i, level: m[1].length, text: m[2].trim() });
  }
  return found;
}

/**
 * Parses and validates a handoff. Throws bad-handoff when the frontmatter is
 * unusable or a required section is missing.
 */
function parseHandoff(text, id, file) {
  const bad = (message) => fail('bad-handoff', `${id}: ${message}`);
  const fm = parseFrontmatter(text);
  if (!fm.data) throw bad('frontmatter is missing');
  if (fm.errors.length > 0) {
    throw bad(`frontmatter: ${fm.errors.map((e) => `line ${e.line} ${e.message}`).join('; ')}`);
  }
  const data = fm.data;
  const missingKeys = ['id', 'status', 'process', 'updated'].filter(
    (k) => typeof data[k] !== 'string' || data[k] === '',
  );
  if (missingKeys.length > 0) throw bad(`frontmatter lacks ${missingKeys.join(', ')}`);
  if (data.id !== id) throw bad(`frontmatter id ${data.id} differs from the file name`);
  if (!STATUSES.includes(data.status)) throw bad(`invalid status ${data.status}`);
  if (Number.isNaN(Date.parse(data.updated))) throw bad(`invalid updated ${data.updated}`);

  const lines = text.split('\n');
  const close = findClose(lines);
  const heads = headings(lines, close + 1);
  const titleHead = heads.find((h) => h.level === 1);

  const sections = new Map();
  for (const h of heads) {
    if (h.level !== 2 || sections.has(h.text)) continue;
    const next = heads.find((n) => n.index > h.index);
    sections.set(h.text, { start: h.index, end: next ? next.index : lines.length });
  }
  const missing = REQUIRED_SECTIONS.filter((name) => !sections.has(name));
  if (missing.length > 0) throw bad(`missing sections: ${missing.join(', ')}`);

  return {
    id,
    file,
    text,
    lines,
    status: data.status,
    process: data.process,
    updated: data.updated,
    title: titleHead ? titleHead.text : '',
    sections,
  };
}

function sectionText(h, name) {
  const s = h.sections.get(name);
  return h.lines.slice(s.start + 1, s.end).join('\n').trim();
}

function goalOf(h) {
  if (h.title) return h.title;
  const firstLine = sectionText(h, 'Goal').split('\n')[0].trim();
  return firstLine || h.id;
}

/** Files listed in the Files section, with the recorded hash (null when missing). */
function fileEntries(h) {
  const s = h.sections.get('Files');
  const out = [];
  for (let i = s.start + 1; i < s.end; i++) {
    const m = FILE_LINE.exec(stripCr(h.lines[i]));
    if (m) out.push({ path: m[1], hash: m[3] ?? null });
  }
  return out;
}

function hashFile(root, rel) {
  const file = path.join(root, rel);
  let stat = null;
  try {
    stat = fs.statSync(file);
  } catch {
    return null;
  }
  if (!stat.isFile()) return null;
  return crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
}

function formatFileLine(rel, hash) {
  return hash ? `- \`${rel}\` — sha256 ${hash}` : `- \`${rel}\` — missing`;
}

/** Returns a copy of `text` with the frontmatter field `key` set to `value`. */
function setFrontmatter(text, key, value) {
  const lines = text.split('\n');
  const close = findClose(lines);
  for (let i = 1; i < close; i++) {
    if (stripCr(lines[i]).startsWith(`${key}:`)) {
      const cr = lines[i].endsWith('\r') ? '\r' : '';
      lines[i] = `${key}: ${value}${cr}`;
      return lines.join('\n');
    }
  }
  throw fail('bad-handoff', `frontmatter has no ${key} field`);
}

function writeAtomic(file, text) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  const tmp = `${file}.tmp-${process.pid}`;
  fs.writeFileSync(tmp, text, 'utf8');
  fs.renameSync(tmp, file);
}

/** Reads and validates every handoff of the campaign. Returns Map id -> handoff. */
function loadAll(root) {
  const dir = topicsDir(root);
  const map = new Map();
  if (!fs.existsSync(dir)) return map;
  for (const name of fs.readdirSync(dir).sort()) {
    if (!name.endsWith('.md') || name === INDEX_NAME) continue;
    const id = name.slice(0, -3);
    if (!ID_PATTERN.test(id)) {
      throw fail('bad-handoff', `${name}: the file name is not a topic id`);
    }
    const file = path.join(dir, name);
    map.set(id, parseHandoff(fs.readFileSync(file, 'utf8'), id, file));
  }
  return map;
}

function getTopic(all, id) {
  checkId(id);
  const h = all.get(id);
  if (!h) throw fail('no-topic', `no topic with id ${id}`);
  return h;
}

function toEntry(h) {
  return {
    id: h.id,
    status: h.status,
    process: h.process,
    goal: goalOf(h),
    updated: h.updated,
    path: h.file,
  };
}

function sortEntries(entries) {
  return entries.sort(
    (a, b) =>
      STATUS_RANK[a.status] - STATUS_RANK[b.status] ||
      Date.parse(b.updated) - Date.parse(a.updated) ||
      (a.id < b.id ? -1 : a.id > b.id ? 1 : 0),
  );
}

function sortedEntries(all) {
  return sortEntries([...all.values()].map(toEntry));
}

function tableCell(s) {
  return String(s).replace(/\s+/g, ' ').replace(/\|/g, '\\|').trim();
}

/** Regenerates index.md from the handoffs on disk. */
function writeIndex(root) {
  const entries = sortedEntries(loadAll(root));
  const rows = entries.map(
    (e) =>
      `| ${e.status} | ${e.id} | ${tableCell(e.process)} | ${tableCell(e.goal)} | ${e.updated} |`,
  );
  const text = [
    INDEX_HEADER,
    '# Topics',
    '',
    '| Status | Id | Process | Goal | Updated |',
    '| --- | --- | --- | --- | --- |',
    ...rows,
  ].join('\n') + '\n';
  writeAtomic(path.join(topicsDir(root), INDEX_NAME), text);
}

function renderNewHandoff({ id, process, goal, updated }) {
  const lines = [
    '---',
    `id: ${id}`,
    'status: active',
    `process: ${process}`,
    `updated: ${updated}`,
    '---',
    '',
    `# ${goal}`,
    '',
  ];
  for (const name of REQUIRED_SECTIONS) {
    lines.push(`## ${name}`, '');
    if (name === 'Goal') lines.push(goal, '');
  }
  return lines.join('\n');
}

/**
 * Creates a topic and makes it the active one. Any other active topic is paused.
 * @returns {{ id: string, path: string }}
 */
export function newTopic(root, { process, goal, now = new Date() } = {}) {
  const base = requireRoot(root);
  checkDate(now);
  if (typeof process !== 'string' || !ID_PATTERN.test(process)) {
    throw fail('bad-input', 'process must be a lowercase slug, such as prepare-session');
  }
  const cleanGoal = checkGoal(goal);
  const slug = slugify(cleanGoal).slice(0, 40).replace(/-+$/, '');
  if (slug === '') {
    throw fail('bad-input', 'goal must contain letters or digits');
  }

  const all = loadAll(base);
  const day = now.toISOString().slice(0, 10);
  let id = `${day}-${slug}`;
  for (let n = 2; all.has(id); n++) {
    id = `${day}-${slug}-${n}`;
  }

  for (const other of all.values()) {
    if (other.status === 'active') {
      writeAtomic(other.file, setFrontmatter(other.text, 'status', 'paused'));
    }
  }

  const file = handoffFile(base, id);
  writeAtomic(
    file,
    renderNewHandoff({ id, process, goal: cleanGoal, updated: now.toISOString() }),
  );
  writeIndex(base);
  return { id, path: file };
}

/**
 * Refreshes a handoff after agents edited its prose: sets `updated`, rewrites
 * the Files section with current hashes, and regenerates the index.
 * @returns {{ id: string, changedSections: string[] }}
 */
export function touchTopic(root, { id, files = [], now = new Date() } = {}) {
  const base = requireRoot(root);
  checkDate(now);
  if (!Array.isArray(files)) {
    throw fail('bad-input', 'files must be an array of paths');
  }
  const added = files.map(checkRelPath);
  const h = getTopic(loadAll(base), id);

  const block = filesBlock(base, h, added);
  const s = h.sections.get('Files');
  const oldText = h.lines.slice(s.start, s.end).join('\n').trim();
  const changedSections = oldText === block.join('\n').trim() ? [] : ['Files'];

  const lines = h.lines.slice();
  lines.splice(s.start, s.end - s.start, ...block);
  const text = setFrontmatter(lines.join('\n'), 'updated', now.toISOString());
  writeAtomic(h.file, text);
  writeIndex(base);
  return { id, changedSections };
}

function setStatus(root, id, status, now) {
  const base = requireRoot(root);
  checkDate(now);
  const all = loadAll(base);
  const h = getTopic(all, id);
  for (const other of all.values()) {
    if (other.id !== id && status === 'active' && other.status === 'active') {
      writeAtomic(other.file, setFrontmatter(other.text, 'status', 'paused'));
    }
  }
  let text = setFrontmatter(h.text, 'status', status);
  text = setFrontmatter(text, 'updated', now.toISOString());
  writeAtomic(h.file, text);
  writeIndex(base);
  return { id, status };
}

/**
 * Makes a topic the single active one; the previously active topic is paused.
 * Sets `updated` on the activated topic.
 */
export function activateTopic(root, { id, now = new Date() } = {}) {
  return setStatus(root, id, 'active', now);
}

/** Closes a topic and sets its `updated`. */
export function closeTopic(root, { id, now = new Date() } = {}) {
  return setStatus(root, id, 'closed', now);
}

/** Lists topics in index order. `path` is the absolute path of the handoff. */
export function listTopics(root) {
  const base = requireRoot(root);
  return sortedEntries(loadAll(base)).map((e) => ({ ...e }));
}

/** The active topic, or null. */
export function activeTopic(root) {
  return listTopics(root).find((e) => e.status === 'active') ?? null;
}

/**
 * Lists the files whose current hash differs from the one recorded in the
 * Files section. A file recorded as missing and still missing is not a change.
 * @returns {{ id: string, changed: string[] }}
 */
export function checkTopic(root, { id } = {}) {
  const base = requireRoot(root);
  const h = getTopic(loadAll(base), id);
  const changed = [];
  for (const entry of fileEntries(h)) {
    if (hashFile(base, entry.path) !== entry.hash) changed.push(entry.path);
  }
  return { id, changed };
}

/** The trimmed text of one required `##` section. */
export function readSection(root, { id, section } = {}) {
  const base = requireRoot(root);
  if (!REQUIRED_SECTIONS.includes(section)) {
    throw fail('bad-input', `unknown section: ${String(section)}`);
  }
  const h = getTopic(loadAll(base), id);
  return sectionText(h, section);
}

/** A one-line value for a section or a list item. */
function checkLine(value, name) {
  if (typeof value !== 'string' || value.trim() === '') {
    throw fail('bad-input', `${name} must be a non-empty string`);
  }
  const s = value.trim();
  if (/[\r\n]/.test(s) || s.startsWith('#')) {
    throw fail('bad-input', `${name} must be one line and must not start with #`);
  }
  return s;
}

/** The whole Files section (heading included) for the files already listed plus `added`. */
function filesBlock(base, h, added) {
  const paths = [];
  for (const rel of [...fileEntries(h).map((e) => e.path), ...added]) {
    if (!paths.includes(rel)) paths.push(rel);
  }
  return paths.length === 0
    ? ['## Files', '']
    : ['## Files', '', ...paths.map((rel) => formatFileLine(rel, hashFile(base, rel))), ''];
}

/** The body lines of a section, without its heading and without blank lines at either end. */
function bodyLines(h, name) {
  const s = h.sections.get(name);
  const body = h.lines.slice(s.start + 1, s.end);
  while (body.length > 0 && body[0].trim() === '') body.shift();
  while (body.length > 0 && body[body.length - 1].trim() === '') body.pop();
  return body;
}

/** The whole section (heading kept from the file) with the given body. */
function sectionLines(h, name, body) {
  const s = h.sections.get(name);
  const heading = h.lines[s.start];
  return body.length === 0 ? [heading, ''] : [heading, '', ...body, ''];
}

/**
 * Writes a handoff with some sections replaced, the given status and `updated`,
 * and regenerates the index. Activating pauses the other active topic.
 * @param {Map<string, string[]>} blocks section name -> full section lines
 */
function commitHandoff(base, all, h, blocks, status, now) {
  const lines = h.lines.slice();
  const items = [...blocks].map(([name, block]) => ({ s: h.sections.get(name), block }));
  items.sort((a, b) => b.s.start - a.s.start);
  for (const { s, block } of items) {
    lines.splice(s.start, s.end - s.start, ...block);
  }
  let text = setFrontmatter(lines.join('\n'), 'status', status);
  text = setFrontmatter(text, 'updated', now.toISOString());
  if (status === 'active') {
    for (const other of all.values()) {
      if (other.id !== h.id && other.status === 'active') {
        writeAtomic(other.file, setFrontmatter(other.text, 'status', 'paused'));
      }
    }
  }
  writeAtomic(h.file, text);
  writeIndex(base);
  return { id: h.id, status };
}

/**
 * Sets the open question and the next step, and makes the topic the active one
 * (a paused or closed topic is reactivated). Other sections are kept.
 * @returns {{ id: string, status: string }}
 */
export function askTopic(root, { id, question, next, now = new Date() } = {}) {
  const base = requireRoot(root);
  checkDate(now);
  const q = checkLine(question, 'question');
  const n = checkLine(next, 'next');
  const all = loadAll(base);
  const h = getTopic(all, id);
  const blocks = new Map([
    ['Questions for the master', sectionLines(h, 'Questions for the master', [`- ${q}`])],
    ['Next step', sectionLines(h, 'Next step', [n])],
  ]);
  return commitHandoff(base, all, h, blocks, 'active', now);
}

/**
 * Records one done item, clears the open question and the next step, refreshes
 * the Files section with the given files, and closes the topic.
 * @returns {{ id: string, status: string }}
 */
export function finishTopic(root, { id, done, files = [], now = new Date() } = {}) {
  const base = requireRoot(root);
  checkDate(now);
  const d = checkLine(done, 'done');
  if (!Array.isArray(files)) {
    throw fail('bad-input', 'files must be an array of paths');
  }
  const added = files.map(checkRelPath);
  const all = loadAll(base);
  const h = getTopic(all, id);
  const blocks = new Map([
    ['Done', sectionLines(h, 'Done', [...bodyLines(h, 'Done'), `- ${d}`])],
    ['Questions for the master', sectionLines(h, 'Questions for the master', ['none'])],
    ['Next step', sectionLines(h, 'Next step', ['none'])],
    ['Files', filesBlock(base, h, added)],
  ]);
  return commitHandoff(base, all, h, blocks, 'closed', now);
}
